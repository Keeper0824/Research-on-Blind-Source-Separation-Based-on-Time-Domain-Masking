import os
import torch
from app.Models.Code.Deep.Model_TasNet import Model


class DeepSignalSeparator:
    def __init__(self, model_type="deep_tasnet", ckpt_path=None, device=None):
        """The inference core class of the deeply optimized version of the model is specially designed for interactive interfaces. :param model_type: "deep_tasnet" or other pretrained model identifier :param ckpt_path: the local.pt weight file path :param device: Forcibly specify the device, cuda or cpu is automatically selected by default"""
        self.device = device if device else ("cuda" if torch.cuda.is_available() else "cpu")
        self.model_type = model_type
        self.ckpt_path = ckpt_path
        self.model = None

        self._load_model()

    def _load_model(self):
        if self.model_type == "deep_tasnet":
            # Initialize the optimal hyperparameters you determined in the Deep version
            self.model = Model(
                enc_dim=512, enc_kernel=16, enc_stride=8,
                bottleneck_channels=128, hidden_channels=256,
                num_blocks=8, num_repeats=3, num_speakers=2
            ).to(self.device)

            if self.ckpt_path and os.path.exists(self.ckpt_path):
                self._load_weights(self.ckpt_path)
            else:
                print(f"Warning: Checkpoint not found at {self.ckpt_path}. Using uninitialized weights.")

        elif self.model_type == "tasnet_deep_comm":
            self.model = Model(
                enc_dim=512, enc_kernel=16, enc_stride=8,
                bottleneck_channels=128, hidden_channels=256,
                num_blocks=8, num_repeats=3, num_speakers=2
            ).to(self.device)

            if self.ckpt_path and os.path.exists(self.ckpt_path):
                self._load_weights(self.ckpt_path)
            else:
                print(f"Warning: Checkpoint not found at {self.ckpt_path}. Using uninitialized weights.")
        else:
            raise ValueError(f"Unsupported model type: {self.model_type}")

        # Locked in inference mode
        self.model.eval()

    def _load_weights(self, path):
        """Reuse the most robust EMA weight loading mechanism you wrote in the local test script"""
        print(f"Loading weights from {path}...")
        ckpt = torch.load(path, map_location=self.device)

        # Prioritize finding and using ema_state for better separation performance
        if isinstance(ckpt, dict):
            if "ema_state" in ckpt:
                print("Found 'ema_state'. Loading EMA weights for better performance...")
                sd = ckpt["ema_state"]
            elif "ema_state_dict" in ckpt:
                print("Found 'ema_state_dict'. Loading EMA weights...")
                sd = ckpt["ema_state_dict"]
            elif "model_state_dict" in ckpt:
                sd = ckpt["model_state_dict"]
            elif "model_state" in ckpt:
                sd = ckpt["model_state"]
            elif "state_dict" in ckpt:
                sd = ckpt["state_dict"]
            else:
                sd = ckpt
        else:
            sd = ckpt

        # Clean the key values of the weight dictionary
        if isinstance(sd, dict):
            # Remove possible module. prefix generated by DataParallel
            sd = {k.replace("module.", "", 1): v for k, v in sd.items()}
            # Remove the counter generated by EMA to prevent errors in strict loading mode
            if "n_averaged" in sd:
                sd.pop("n_averaged")

        self.model.load_state_dict(sd, strict=True)
        print("Model weights loaded successfully.")

    @torch.no_grad()
    def separate(self, mix_waveform):
        """Receives a mixed audio Tensor and outputs a separated audio Tensor. :param mix_waveform: Tensor with shape (1, T) or (T,) :return: The separated Tensor with shape (num_speakers, T) (located on the CPU to facilitate subsequent saving or plotting)"""
        # Dimension sorting, adapting network input (Batch, 1, Time)
        if mix_waveform.dim() == 1:
            mix_waveform = mix_waveform.unsqueeze(0).unsqueeze(0)
        elif mix_waveform.dim() == 2:
            mix_waveform = mix_waveform.unsqueeze(1)

        mix_waveform = mix_waveform.to(self.device)

        est_sources = self.model(mix_waveform)  # Enable bfloat16 mixed-precision accelerated inference

        # output(1, 2, T_est)
        min_len = min(est_sources.shape[-1], mix_waveform.shape[-1])
        est_sources = est_sources[..., :min_len]

        # Truncate the little extra length that may be due to convolution padding
        return est_sources.squeeze(0).cpu()